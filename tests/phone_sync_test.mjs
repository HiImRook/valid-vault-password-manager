import { test, before, after } from 'node:test'
import assert from 'node:assert/strict'
import { REPO_ROOT, PASSWORD, SECOND_PASSWORD, KEY_PROTECTION, KEY_ANSWERS, startServer, launchBrowser, fillDialog, dialogError } from './harness.mjs'
import { newPhone, waitMessage, phoneTab, pickFile, setUpWithPassword, addLogin, revealAll } from './phone_harness.mjs'

const SEED_PHRASE = 'abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon about'

let server
let browser
let vaultFromA
let keyFromA
let vaultFromB

before(async () => {
  server = await startServer(REPO_ROOT)
  browser = await launchBrowser()
})

after(async () => {
  await browser.close()
  await server.close()
})

test('phone A exports a vault with every section and a protected key', async () => {
  const a = await newPhone(browser, server.url, { noBiometrics: true })
  const { page } = a
  await setUpWithPassword(a)
  await addLogin(a, 'example.com', 'alice', 'alice-pw-1!')
  await addLogin(a, 'mail.example.com', 'alice@mail.com', 'mail-pw-2!')
  await phoneTab(page, 'webcreds')
  await page.click('#btn-add-webcred')
  await fillDialog(page, [PASSWORD])
  await fillDialog(page, ['Wi-Fi', 'Home', 'wifi-secret'])
  await waitMessage(page, 'msg-webcreds', /Saved/)
  await phoneTab(page, 'bookmarks')
  await page.click('#btn-add-bookmark')
  await fillDialog(page, ['example.com/docs', 'Docs'])
  await waitMessage(page, 'msg-bookmarks', /Bookmark saved/)
  await phoneTab(page, 'personal')
  await page.click('#personalinfo-content .gate button')
  await fillDialog(page, [PASSWORD])
  await page.locator('#personalinfo-content .field-row button', { hasText: 'Edit' }).first().click()
  await fillDialog(page, [PASSWORD])
  await fillDialog(page, ['Alice'])
  await waitMessage(page, 'msg-personalinfo', /Saved/)
  await phoneTab(page, 'wallets')
  await page.click('#wallets-content .wv-gate button')
  await fillDialog(page, [PASSWORD])
  await page.click('#btn-add-wallet')
  await page.fill('.wv-editor .wv-fields input', 'Main')
  await page.locator('.wv-word-input').first().fill(SEED_PHRASE)
  await page.locator('.wv-editor button', { hasText: 'Done' }).click()
  await page.waitForTimeout(400)
  const cancelNotes = page.locator('.wv-editor button', { hasText: 'Cancel' })
  if (await cancelNotes.count()) await cancelNotes.click()
  await page.waitForTimeout(300)
  assert.equal(await page.locator('.wv-wallet-name').count(), 1)
  await phoneTab(page, 'sync')
  await page.click('#btn-export-vault')
  await fillDialog(page, [PASSWORD])
  await fillDialog(page, ['download'])
  await waitMessage(page, 'msg-sync', /Saved to Downloads/)
  await page.click('#btn-export-key')
  await fillDialog(page, [PASSWORD])
  await fillDialog(page, ['weak', 'weak'])
  assert.ok((await dialogError(page) || '').length > 0)
  await page.locator('.wv-dialog-overlay .wv-dialog-actions button').first().click()
  await page.click('#btn-export-key')
  await fillDialog(page, [PASSWORD])
  await fillDialog(page, KEY_PROTECTION)
  await page.waitForTimeout(1500)
  await fillDialog(page, ['share'])
  await waitMessage(page, 'msg-sync', /Key sent/)
  const files = await page.evaluate(() => ({ downloads: window.__downloads, cache: window.__fsFiles || {}, deleted: window.__deleted, shared: window.__shared }))
  const [vaultName, vaultText] = Object.entries(files.downloads).find(([n]) => n.endsWith('.vault'))
  vaultFromA = { name: vaultName, text: vaultText }
  assert.match(vaultName, /^valid-vault-backup(-My-Master-Key)?\.vault$/)
  const sharedName = files.shared[0].split('/').pop()
  assert.ok(files.deleted.includes(sharedName))
  assert.ok(!Object.keys(files.cache).some((n) => n.endsWith('.vaultkey')))
  const keyPackage = await page.evaluate(() => new Promise((resolve) => {
    const request = indexedDB.open('ValidVault')
    request.onsuccess = () => { const get = request.result.transaction('auth').objectStore('auth').get('primary'); get.onsuccess = () => resolve(JSON.stringify(get.result.keyPackage)) }
  }))
  keyFromA = { name: 'my-master-key.vaultkey', text: keyPackage }
  const bundle = JSON.parse(vaultText)
  assert.deepEqual(['vault', 'webcreds', 'personalInfo', 'bookmarks', 'wallets'].filter((k) => !bundle[k]), [])
  await a.context.close()
})

test('phone B sets up from the key file and merges the vault', async () => {
  const b = await newPhone(browser, server.url)
  const { page } = b
  await pickFile(page, () => page.click('#btn-setup-file-key'), keyFromA)
  await fillDialog(page, [KEY_ANSWERS[0], KEY_ANSWERS[1], KEY_ANSWERS[2], 'wrong'])
  assert.match(await dialogError(page) || '', /Wrong passphrase/)
  await fillDialog(page, KEY_ANSWERS)
  await fillDialog(page, ['device'])
  await fillDialog(page, [SECOND_PASSWORD, SECOND_PASSWORD])
  await page.waitForSelector('#view-app:not(.hidden)')
  assert.equal(await page.locator('.wv-dialog-overlay .wv-dialog-title').textContent(), 'Bring your vault')
  await pickFile(page, () => fillDialog(page, ['file']), vaultFromA)
  assert.match(await waitMessage(page, 'msg-sync', /Vault merged|up to date|failed/), /Vault merged/)
  assert.deepEqual(await revealAll(b), ['alice=alice-pw-1!', 'alice@mail.com=mail-pw-2!'])
  await phoneTab(page, 'bookmarks')
  assert.deepEqual(await page.locator('.bm-title').allTextContents(), ['Docs'])
  await phoneTab(page, 'wallets')
  await page.click('#wallets-content .wv-gate button')
  await page.waitForTimeout(400)
  assert.deepEqual(await page.locator('.wv-wallet-name').allTextContents(), ['Main'])
  await phoneTab(page, 'sync')
  await pickFile(page, () => page.click('#btn-import-vault'), vaultFromA)
  await page.waitForTimeout(300)
  assert.match(await waitMessage(page, 'msg-sync', /up to date|merged|failed/), /Already up to date/)
  await addLogin(b, 'example.com', 'bob', 'bob-pw-3!')
  await addLogin(b, 'example.com', 'alice', 'alice-new-4!')
  await phoneTab(page, 'sync')
  await page.click('#btn-export-vault')
  await fillDialog(page, ['download'])
  await waitMessage(page, 'msg-sync', /Saved to Downloads/)
  const [name, text] = Object.entries(await page.evaluate(() => window.__downloads)).find(([n]) => n.endsWith('.vault'))
  vaultFromB = { name, text }
  assert.deepEqual(page.errors, [])
  await b.context.close()
})

test('phone A merges B with no duplicates and keeps the newest passwords', async () => {
  const a = await newPhone(browser, server.url, { noBiometrics: true })
  const { page } = a
  await pickFile(page, () => page.click('#btn-setup-file-key'), keyFromA)
  await fillDialog(page, KEY_ANSWERS)
  await fillDialog(page, [PASSWORD, PASSWORD])
  await page.waitForSelector('#view-app:not(.hidden)')
  await pickFile(page, () => fillDialog(page, ['file']), vaultFromA)
  await waitMessage(page, 'msg-sync', /Vault merged/)
  await pickFile(page, () => page.click('#btn-import-vault'), vaultFromB)
  await fillDialog(page, [PASSWORD])
  await waitMessage(page, 'msg-sync', /Vault merged/)
  const merged = await revealAll(a)
  assert.deepEqual(merged, ['alice=alice-new-4!', 'alice@mail.com=mail-pw-2!', 'bob=bob-pw-3!'])
  await pickFile(page, async () => { await phoneTab(page, 'sync'); await page.click('#btn-import-vault') }, vaultFromA)
  await fillDialog(page, [PASSWORD])
  await waitMessage(page, 'msg-sync', /up to date|merged/)
  assert.deepEqual(await revealAll(a), merged)
  assert.equal(await page.locator('#credentials-list .item').count(), 3)
  assert.equal(await page.locator('#credentials-list .extra-label', { hasText: 'Previous password' }).count(), 1)
  await a.context.close()
})

test('importing a different key warns, replaces this phone vault, and survives lock and unlock', async () => {
  const c = await newPhone(browser, server.url, { noBiometrics: true })
  const { page } = c
  await setUpWithPassword(c)
  await addLogin(c, 'other.com', 'carol', 'carol-pw-5!')
  await phoneTab(page, 'sync')
  await pickFile(page, () => page.click('#btn-import-vault'), vaultFromA)
  await fillDialog(page, [PASSWORD])
  assert.match(await waitMessage(page, 'msg-sync', /failed/), /different master key/)
  await pickFile(page, () => page.click('#btn-import-key'), keyFromA)
  await fillDialog(page, [PASSWORD])
  await fillDialog(page, KEY_ANSWERS)
  assert.match(await page.locator('.wv-dialog-overlay .wv-dialog-title').textContent(), /Replace this phone/)
  await fillDialog(page, [])
  await fillDialog(page, [PASSWORD])
  await waitMessage(page, 'msg-sync', /Master key imported/)
  await pickFile(page, () => page.click('#btn-import-vault'), vaultFromA)
  await fillDialog(page, [PASSWORD])
  await waitMessage(page, 'msg-sync', /Vault merged/)
  const shown = await revealAll(c)
  assert.deepEqual(shown, ['alice=alice-pw-1!', 'alice@mail.com=mail-pw-2!'])
  await page.click('#btn-lock')
  await page.fill('#input-unlock-password', PASSWORD)
  await page.click('#btn-unlock-pw')
  await page.waitForSelector('#view-app:not(.hidden)')
  assert.deepEqual(await revealAll(c), shown)
  await c.context.close()
})
